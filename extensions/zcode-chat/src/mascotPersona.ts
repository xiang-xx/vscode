/**
 * Shared speaking styles for chat mascots. A character starts on the default
 * below; the background menu can switch any queued character to another one.
 * `voice` is told to the line model. `lines` are the local bubble text when
 * that call is skipped or fails, so the fallback still sounds like the pick.
 */

export const MASCOT_GIFT_GLYPHS = ['☕', '🍪', '📖', '🐟', '⭐', '🎵', '🍀', '🧋', '💡'] as const;
export type MascotGiftGlyph = typeof MASCOT_GIFT_GLYPHS[number];

export interface MascotPersonaLines {
	tap: readonly string[];
	head: readonly string[];
	ear: readonly string[];
	foot: readonly string[];
	combo: readonly string[];
	pet: readonly string[];
	chatter: readonly string[];
	dispatch: readonly string[];
	complete: readonly string[];
	gifts: Readonly<Record<MascotGiftGlyph, string>>;
}

export interface MascotPersona {
	id: string;
	/** Name shown in the picker. */
	label: string;
	/** Picker group. */
	group: '性格' | '身份';
	/** One line under the picker, for the person choosing. */
	hint: string;
	/** How the line model should talk. */
	voice: string;
	lines: MascotPersonaLines;
}

