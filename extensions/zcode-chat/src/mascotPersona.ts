const FALLBACK_CYCLE = ['soft', 'sunny', 'cool', 'gentle', 'shy', 'sharp', 'sleepy', 'senior'] as const;

export function defaultMascotPersonaId(catalogId: string): string {
	const named = DEFAULT_BY_ID[catalogId];
	if (named && personaById.has(named)) {
		return named;
	}
	let n = 0;
	for (let i = 0; i < catalogId.length; i++) {
		n = (n + catalogId.charCodeAt(i)) % FALLBACK_CYCLE.length;
	}
	return FALLBACK_CYCLE[n];
}

/** Saved pick wins. Anything else falls back to that character's default. */
export function resolveMascotPersonaId(catalogId: string, overrides?: { [id: string]: string }): string {
	const chosen = overrides?.[catalogId];
	if (chosen && personaById.has(chosen)) {
		return chosen;
	}
	return defaultMascotPersonaId(catalogId);
}
